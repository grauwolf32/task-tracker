#!/usr/bin/env python3
"""Validate the opt-in file-tasks-v1 format and generate its backlog."""
import argparse
from datetime import date
import html
from pathlib import Path
import re
import subprocess
import sys
from urllib.parse import quote

import yaml

MARKER = '<!-- Generated by manage-project-tasks; do not edit. -->'
STATUSES = {'pending', 'in_progress', 'deferred', 'completed', 'archived'}
KINDS = {'feature', 'defect', 'chore'}
PRIORITIES = {'P0', 'P1', 'P2', 'P3'}
MAX_FILES = 20000
MAX_BYTES = 1024 * 1024
MAX_TOTAL = 64 * 1024 * 1024


class Invalid(ValueError):
    pass


class UniqueLoader(yaml.SafeLoader):
    pass


def unique_mapping(loader, node):
    result = {}
    for key_node, value_node in node.value:
        key = loader.construct_object(key_node, deep=True)
        if not isinstance(key, str) or key in result:
            raise Invalid('YAML mapping keys must be unique strings')
        result[key] = loader.construct_object(value_node, deep=True)
    return result


UniqueLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, unique_mapping)


def load(path):
    if path.is_symlink() or not path.is_file() or path.stat().st_size > MAX_BYTES:
        raise Invalid(f'{path.name}: expected a regular YAML file up to 1 MiB')
    try:
        data = yaml.load(path.read_text(encoding='utf-8'), Loader=UniqueLoader)
    except (OSError, UnicodeError, yaml.YAMLError, RecursionError, ValueError) as exc:
        raise Invalid(f'{path.name}: invalid YAML: {exc}') from exc
    if not isinstance(data, dict):
        raise Invalid(f'{path.name}: expected a YAML mapping')
    return data


def nonempty(value):
    return isinstance(value, str) and bool(value.strip())


def dated(value):
    try:
        date.fromisoformat(str(value))
        return True
    except ValueError:
        return False


def validate(root):
    root = Path(root).resolve()
    policy = load(root / 'index.yml')
    if policy.get('tracker_format') != 'file-tasks-v1':
        raise Invalid('This helper only supports tracker_format: file-tasks-v1; use the existing project tools.')
    errors = []

    def check(condition, message):
        if not condition:
            errors.append(message)

    check(nonempty((policy.get('project') or {}).get('name')) if isinstance(policy.get('project'), dict) else False,
          'index.yml: project.name is required')
    execution = policy.get('execution_policy')
    require_commit = execution.get('require_implementation_commit') if isinstance(execution, dict) else None
    check(isinstance(require_commit, bool), 'index.yml: require_implementation_commit must be boolean')
    catalog = load(root / 'epics.yml').get('epics')
    check(isinstance(catalog, list), 'epics.yml: epics must be a list')
    epics = set()
    for epic in catalog if isinstance(catalog, list) else []:
        valid = isinstance(epic, dict) and all(nonempty(epic.get(k)) for k in ('id', 'title', 'scope'))
        check(valid, 'epics.yml: each epic needs id, title and scope')
        if valid:
            check(epic['id'] not in epics, f"duplicate epic: {epic['id']}")
            epics.add(epic['id'])
    done = root / 'done'
    if done.is_symlink():
        raise Invalid('done/ must not be a symlink')
    paths = sorted(p for folder in (root, done) for p in folder.glob('*')
                   if p.suffix in {'.yml', '.yaml'} and p.name not in {'index.yml', 'epics.yml'})
    if len(paths) > MAX_FILES:
        raise Invalid('too many tasks: maximum 20,000 files')
    tasks = {}
    total = 0
    for path in paths:
        total += path.lstat().st_size
        if total > MAX_TOTAL:
            raise Invalid('task YAML exceeds 64 MiB')
        task = load(path)
        tag = str(path.relative_to(root))
        task_id = task.get('id')
        valid_id = isinstance(task_id, str) and re.fullmatch(r'[A-Z][A-Z0-9]*-\d{3,}', task_id)
        check(valid_id, f'{tag}: invalid task id')
        if not valid_id:
            continue
        check(task_id not in tasks, f'{tag}: duplicate id {task_id}')
        if task_id in tasks:
            continue
        tasks[task_id] = (path, task)
        check(path.stem == task_id.lower() or path.stem.startswith(task_id.lower() + '-'), f'{tag}: filename must start with lowercase task id')
        for field in ('title', 'goal', 'epic'):
            check(nonempty(task.get(field)), f'{tag}: {field} must be nonempty text')
        check(task.get('schema_version') == '1.0', f'{tag}: schema_version must be "1.0"')
        status = task.get('status')
        check(isinstance(status, str) and status in STATUSES, f'{tag}: invalid status')
        check(isinstance(task.get('kind'), str) and task['kind'] in KINDS, f'{tag}: invalid kind')
        check(isinstance(task.get('priority'), str) and task['priority'] in PRIORITIES, f'{tag}: invalid priority')
        check(isinstance(task.get('epic'), str) and task['epic'] in epics, f'{tag}: undeclared epic')
        check((path.parent == done) == (status in ('completed', 'archived')), f'{tag}: status does not match open/done location')
        deps = task.get('depends_on')
        valid_deps = isinstance(deps, list) and all(isinstance(dep, str) for dep in deps)
        check(valid_deps and len(deps) == len(set(deps)) if valid_deps else False, f'{tag}: depends_on must be unique task ids')
        scope = task.get('scope')
        check(isinstance(scope, dict) and all(isinstance(scope.get(k), list) and all(nonempty(x) for x in scope[k]) for k in ('in', 'out')) and bool(scope['in']), f'{tag}: scope needs nonempty in and an out list')
        criteria = task.get('acceptance_criteria')
        check(isinstance(criteria, list) and bool(criteria), f'{tag}: acceptance_criteria must be a nonempty list')
        ids = set()
        for criterion in criteria if isinstance(criteria, list) else []:
            valid = isinstance(criterion, dict) and nonempty(criterion.get('id')) and (nonempty(criterion.get('text')) or all(nonempty(criterion.get(k)) for k in ('given', 'when', 'then')))
            check(valid, f'{tag}: each acceptance criterion needs id and text or given/when/then')
            if valid:
                check(criterion['id'] not in ids, f'{tag}: duplicate acceptance id')
                ids.add(criterion['id'])
        tests = task.get('tests')
        check(isinstance(tests, list) and bool(tests), f'{tag}: tests must be a nonempty list')
        commands, covered = set(), set()
        for test in tests if isinstance(tests, list) else []:
            valid = isinstance(test, dict) and nonempty(test.get('command')) and isinstance(test.get('covers'), list) and bool(test['covers']) and all(isinstance(x, str) for x in test['covers'])
            check(valid, f'{tag}: tests need command and nonempty covers')
            if valid:
                check(test['command'] not in commands, f'{tag}: duplicate test command')
                commands.add(test['command'])
                covered.update(test['covers'])
        check(covered == ids, f'{tag}: test covers must match all declared acceptance ids')
        if status in ('deferred', 'archived'):
            disposition = task.get('disposition')
            valid = isinstance(disposition, dict) and all(nonempty(disposition.get(k)) for k in ('reason', 'reopen_when')) and dated(disposition.get('date')) and isinstance(disposition.get('previous_status'), str) and disposition['previous_status'] in STATUSES
            check(valid, f'{tag}: disposition needs reason, date, previous_status and reopen_when')
        if status == 'completed':
            completion = task.get('completion')
            valid = isinstance(completion, dict) and nonempty(completion.get('summary')) and dated(completion.get('verified_at')) and isinstance(completion.get('tests'), list)
            check(valid, f'{tag}: completion needs summary, verified_at and test evidence')
            results = {}
            for result in completion['tests'] if valid else []:
                valid_result = isinstance(result, dict) and nonempty(result.get('command')) and result.get('result') == 'passed' and nonempty(result.get('evidence'))
                check(valid_result, f'{tag}: every completion test needs passed result and actual evidence')
                if valid_result:
                    check(result['command'] not in results, f'{tag}: duplicate completion test')
                    results[result['command']] = result
            check(set(results) == commands, f'{tag}: completion evidence must cover exactly the declared commands')
            if require_commit:
                commit = task.get('implementation_commit')
                valid_hash = isinstance(commit, str) and re.fullmatch(r'(?:[0-9a-f]{40}|[0-9a-f]{64})', commit)
                check(valid_hash, f'{tag}: full implementation_commit required')
                if valid_hash:
                    found = subprocess.run(['git', '-C', str(root), 'cat-file', '-t', commit], capture_output=True, text=True, check=False)
                    check(found.returncode == 0 and found.stdout.strip() == 'commit', f'{tag}: implementation_commit is not an existing commit')
    for task_id, (_, task) in tasks.items():
        for dep in task.get('depends_on', []) if isinstance(task.get('depends_on'), list) else []:
            if not isinstance(dep, str):
                continue
            check(dep in tasks, f'{task_id}: unknown dependency {dep}')
            if dep in tasks and task.get('status') == 'in_progress':
                check(tasks[dep][1].get('status') == 'completed', f'{task_id}: dependency {dep} is not completed')
        if 'introduced_by' in task:
            check(isinstance(task['introduced_by'], str) and task['introduced_by'] in tasks and task['introduced_by'] != task_id, f'{task_id}: introduced_by must name another known task')
    # Iterative DFS avoids overflowing the Python stack on large task chains.
    colors = {}
    for task_id in tasks:
        stack = [(task_id, False)]
        while stack:
            node, leaving = stack.pop()
            if leaving:
                colors[node] = 2
                continue
            if colors.get(node) == 2:
                continue
            if colors.get(node) == 1:
                check(False, f'dependency cycle involving {node}')
                continue
            colors[node] = 1
            stack.append((node, True))
            deps = tasks[node][1].get('depends_on')
            for dep in reversed(deps if isinstance(deps, list) else []):
                if isinstance(dep, str) and dep in tasks:
                    stack.append((dep, False))
    milestones = policy.get('milestones')
    check(isinstance(milestones, list), 'index.yml: milestones must be a list')
    milestone_definitions = {}
    for milestone in milestones if isinstance(milestones, list) else []:
        valid = isinstance(milestone, dict) and all(nonempty(milestone.get(k)) for k in ('id', 'epic', 'outcome', 'exit_task'))
        check(valid, 'index.yml: milestone needs id, epic, outcome and exit_task')
        if valid:
            check(milestone['id'] not in milestone_definitions, 'index.yml: duplicate milestone')
            milestone_definitions[milestone['id']] = milestone
            check(milestone['epic'] in epics, f"{milestone['id']}: unknown epic")
            check(milestone['exit_task'] in tasks, f"{milestone['id']}: unknown exit_task")
            if milestone['exit_task'] in tasks:
                exit_task = tasks[milestone['exit_task']][1]
                check(exit_task.get('epic') == milestone['epic'], f"{milestone['id']}: exit_task epic must match milestone epic")
                check(exit_task.get('milestone') == milestone['id'], f"{milestone['id']}: exit_task must belong to this milestone")
    for task_id, (_, task) in tasks.items():
        if 'milestone' in task:
            known = isinstance(task['milestone'], str) and task['milestone'] in milestone_definitions
            check(known, f'{task_id}: undeclared milestone')
            if known:
                check(task.get('epic') == milestone_definitions[task['milestone']]['epic'], f'{task_id}: task epic must match milestone epic')
    if errors:
        raise Invalid('\n'.join(errors))
    return tasks


def backlog(root, tasks):
    def text(value):
        return re.sub(r'([\\`*_{}\[\]()|])', r'\\\1', html.escape(str(value))).replace('\n', ' ').replace('\r', ' ')
    rows = [MARKER, '# Backlog', '', '| ID | Task | Status | Priority | Epic | Dependencies |', '| --- | --- | --- | --- | --- | --- |']
    rank = {'in_progress': 0, 'pending': 1, 'deferred': 2, 'completed': 3, 'archived': 4}
    ordered = sorted(tasks.items(), key=lambda item: (rank[item[1][1]['status']], item[1][1]['priority'], item[0]))
    for task_id, (path, task) in ordered:
        link = quote(path.relative_to(root).as_posix())
        rows.append(f"| [{task_id}]({link}) | {text(task['title'])} | {task['status']} | {task['priority']} | {text(task['epic'])} | {text(', '.join(task['depends_on'])) or '—'} |")
    return '\n'.join(rows) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('validate', 'backlog'))
    parser.add_argument('--tasks', type=Path, default=Path('tasks'))
    parser.add_argument('--check', action='store_true', help='Compare generated backlog without writing')
    args = parser.parse_args()
    if args.check and args.command != 'backlog':
        parser.error('--check is only supported for backlog')
    try:
        root = args.tasks.resolve()
        tasks = validate(root)
        if args.command == 'backlog':
            output = backlog(root, tasks)
            destination = root / 'BACKLOG.md'
            if destination.is_symlink():
                raise Invalid('BACKLOG.md must not be a symlink')
            existing = destination.read_text(encoding='utf-8') if destination.exists() else None
            if args.check:
                if existing != output:
                    raise Invalid('BACKLOG.md is missing or stale')
            else:
                if existing is not None and not existing.startswith(MARKER + '\n'):
                    raise Invalid('refusing to overwrite a manually maintained BACKLOG.md')
                destination.write_text(output, encoding='utf-8')
        print(f'OK: {len(tasks)} tasks')
    except (Invalid, OSError, UnicodeError) as exc:
        print(str(exc), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
